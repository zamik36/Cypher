use std::path::Path;

include!("src/commands/names.rs");

/// The permission set that grants every app command; capabilities name it.
const COMMAND_SET: &str = "app-commands";

fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    embed_windows_manifest();
    println!("cargo:rerun-if-changed=src/commands/names.rs");
    write_command_set()?;
    let windows = tauri_build::WindowsAttributes::new_without_app_manifest();
    let manifest = tauri_build::AppManifest::new().commands(COMMANDS);
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .windows_attributes(windows)
            .app_manifest(manifest),
    )?;
    Ok(())
}

/// Next to the `allow-<command>` permissions tauri-build generates from
/// [`COMMANDS`]: one set holding all of them, so a capability grants the
/// list rather than repeating it.
fn write_command_set() -> std::io::Result<()> {
    let dir = Path::new("permissions").join("autogenerated");
    std::fs::create_dir_all(&dir)?;
    let allowed: Vec<String> = COMMANDS
        .iter()
        .map(|c| format!("  \"allow-{}\",\n", c.replace('_', "-")))
        .collect();
    let toml = format!(
        "# Automatically generated by build.rs from src/commands/names.rs - DO NOT EDIT!\n\n\
         [[set]]\n\
         identifier = \"{COMMAND_SET}\"\n\
         description = \"Every command of the app's UI.\"\n\
         permissions = [\n{}]\n",
        allowed.concat()
    );
    let path = dir.join(format!("{COMMAND_SET}.toml"));
    // Rewriting an unchanged file would make the next build run this again.
    if std::fs::read_to_string(&path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&path, toml)?;
    }
    Ok(())
}

/// tauri-build embeds its manifest only into the app binary; linking it into
/// every target lets the test executables load too.
fn embed_windows_manifest() {
    let msvc = std::env::var("CARGO_CFG_TARGET_ENV").is_ok_and(|env| env == "msvc");
    if !msvc {
        return;
    }
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR")).join("windows-app-manifest.xml");
    println!("cargo:rerun-if-changed={}", manifest.display());
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
}
